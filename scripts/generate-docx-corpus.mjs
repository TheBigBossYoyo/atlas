const FIXTURES = [
  fixturePlainParagraphsStyles,
  fixtureHeaderFooterPageNumbers,
  fixtureFootnotesEndnotes,
  fixtureTableFixedGridMergedCells,
  fixtureTableStyledBanded,
  fixtureImageInline,
  fixtureImageAnchoredFloating,
  fixtureListsBulletsNumbered,
  fixtureHyperlinksBookmarks,
  fixtureCommentsWithReply,
  fixtureTrackedChangesInsertDelete,
  fixtureSectionBreaks,
  fixtureContentControlAlternateContent,
]

async function buildFixture(build) {
  const { id, document, postProcess } = build()
  const packed = await Packer.toBuffer(document)
  const files = await unzipToFiles(packed)
  // Every fixture except the one built to exercise it keeps a clean surface
  // for the feature it targets — see stripAutoGeneratedFootnotesEndnotes's
  // own doc comment for why this is necessary (DXS-01).
  if (id !== 'footnotes-endnotes') {
    stripAutoGeneratedFootnotesEndnotes(files)
  }
  if (postProcess) postProcess(files)
  stabilizeArchive(files)
  const finalBuffer = await zipFromFiles(files)
  const outPath = path.join(OUT_DIR, `${id}.docx`)
  await writeFile(outPath, finalBuffer)
  return { id, outPath, bytes: finalBuffer.length }
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true })
  const results = []
  for (const build of FIXTURES) {
    results.push(await buildFixture(build))
  }
  console.log(`Generated ${results.length} corpus fixtures into ${path.relative(process.cwd(), OUT_DIR)}:`)
  for (const result of results) {
    console.log(`  ${result.id}.docx (${result.bytes} bytes)`)
  }
}

await main()
