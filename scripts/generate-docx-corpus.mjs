function fixtureCommentsWithReply() {
  const id = 'comments-with-reply'
  const document = new Document({
    creator: AUTHOR,
    lastModifiedBy: AUTHOR,
    comments: {
      children: [
        {
          id: 1,
          author: 'Reviewer One',
          initials: 'R1',
          date: FIXED_DATE,
          children: [new Paragraph({ children: [new TextRun('This phrase needs clarification.')] })],
        },
        {
          id: 2,
          author: 'Reviewer Two',
          initials: 'R2',
          date: FIXED_DATE,
          children: [new Paragraph({ children: [new TextRun('Agreed — I will rewrite it.')] })],
        },
      ],
    },
    sections: [
      {
        children: [
          introParagraph(id),
          new Paragraph({
            children: [
              new TextRun('This document has a '),
              new CommentRangeStart(1),
              new TextRun('commented phrase'),
              new CommentRangeEnd(1),
              new CommentReference(1),
              new TextRun(' and a '),
              new CommentRangeStart(2),
              new TextRun('replied-to phrase'),
              new CommentRangeEnd(2),
              new CommentReference(2),
              new TextRun('.'),
            ],
          }),
        ],
      },
    ],
  })

  // `docx` has no option for `w:comment/@w:parentId` (comment threading), so
  // splice it in directly: comment 2 is a reply to comment 1.
  const postProcess = (files) => {
    const commentsPath = 'word/comments.xml'
    const xml = files.get(commentsPath)
    if (typeof xml !== 'string' || !xml.includes('w:id="2"')) {
      throw new Error(`${id}: expected ${commentsPath} to contain a comment with w:id="2"`)
    }
    files.set(commentsPath, xml.replace(/(<w:comment\b[^>]*\bw:id="2")/, '$1 w:parentId="1"'))
  }

  return { id, document, postProcess }
}

