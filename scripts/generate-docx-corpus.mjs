// Deterministic generator for the DOCX round-trip fidelity corpus
// (P0.5 / QA-09 / DXS-17 — see .sisyphus/plans/atlas-phase3-improvement.md).
//
// Produces one small, focused `.docx` fixture per real-world OOXML feature
// listed in the P0.5 task text into src/docx/__fixtures__/corpus/, using the
// `docx` npm package for anything it can express natively and a small
// amount of JSZip-based XML surgery (scripts/lib/corpusArchive.mjs) for the
// handful of constructs it cannot (content controls, mc:AlternateContent,
// comment replies, a custom banded table style).
//
// Every fixture's body starts with a plain, single-run intro paragraph
// (see `introParagraph`) so the round-trip test harness
// (src/docx/__tests__/roundtrip.corpus.test.ts) can apply the same trivial
// "insert text into the first paragraph" edit to every fixture uniformly.
//
// Run with: node scripts/generate-docx-corpus.mjs
