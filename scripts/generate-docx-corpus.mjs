// 13. Content control (w:sdt) + mc:AlternateContent shape
// ---------------------------------------------------------------------------
const SDT_MARKER = 'This paragraph lives inside a content control.'
const ALT_CONTENT_MARKER = 'ATLAS_ALTCONTENT_PLACEHOLDER'

// `xmlns:a` (DrawingML main) is declared right here on `<a:graphic>`, NOT
// assumed to already be in scope from the document root — `docx` (the npm
// package the rest of this generator uses) never declares it at the root
// either, only locally on each `<a:graphic>`/`<a:graphicFrameLocks>` it
// emits (see `image-inline.docx`'s own `word/document.xml`). This block is
// hand-authored XML surgery, not `docx`-generated, so it does not get that
// declaration for free — omitting it left this fixture with an undeclared
// namespace prefix (caught by `scripts/validate-office-file.mjs`), which is
// exactly the "not namespace-well-formed" defect a real Word install
// refuses/repairs a file over.
const ALT_CONTENT_RUN_XML = `
<w:r>
  <mc:AlternateContent>
    <mc:Choice Requires="wps">
      <w:drawing>
        <wp:inline distT="0" distB="0" distL="0" distR="0">
          <wp:extent cx="914400" cy="457200"/>
          <wp:effectExtent l="0" t="0" r="0" b="0"/>
          <wp:docPr id="1" name="Atlas Rectangle"/>
          <wp:cNvGraphicFramePr/>
          <a:graphic xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">
            <a:graphicData uri="http://schemas.microsoft.com/office/word/2010/wordprocessingShape">
              <wps:wsp>
                <wps:cNvSpPr/>
                <wps:spPr>
                  <a:xfrm><a:off x="0" y="0"/><a:ext cx="914400" cy="457200"/></a:xfrm>
                  <a:prstGeom prst="rect"><a:avLst/></a:prstGeom>
                  <a:solidFill><a:srgbClr val="4472C4"/></a:solidFill>
                </wps:spPr>
              </wps:wsp>
            </a:graphicData>
          </a:graphic>
        </wp:inline>
      </w:drawing>
    </mc:Choice>
    <mc:Fallback>
      <w:pict>
        <v:rect style="width:72pt;height:36pt" fillcolor="#4472C4"/>
      </w:pict>
    </mc:Fallback>
  </mc:AlternateContent>
</w:r>`.replace(/>\s+</g, '><').trim()

function fixtureContentControlAlternateContent() {
  const id = 'content-control-alternate-content'
  const document = new Document({
    creator: AUTHOR,
    lastModifiedBy: AUTHOR,
    sections: [
      {
        children: [
          introParagraph(id),
          new Paragraph({ children: [new TextRun(SDT_MARKER)] }),
          new Paragraph({ children: [new TextRun('Before the shape: '), new TextRun(ALT_CONTENT_MARKER), new TextRun(' after the shape.')] }),
        ],
      },
    ],
  })

  const postProcess = (files) => {
    const documentPath = 'word/document.xml'
    const xml = files.get(documentPath)
    if (typeof xml !== 'string') {
      throw new Error(`${id}: expected ${documentPath} to exist`)
    }
    const wrappedInSdt = wrapParagraphContaining(
      xml,
      SDT_MARKER,
      (paragraphXml) =>
        '<w:sdt><w:sdtPr><w:id w:val="100001"/><w:alias w:val="Atlas Content Control"/><w:tag w:val="atlasCorpusSdt"/><w:text/></w:sdtPr>' +
        `<w:sdtContent>${paragraphXml}</w:sdtContent></w:sdt>`,
    )
    const withAltContent = replaceRunContaining(wrappedInSdt, ALT_CONTENT_MARKER, ALT_CONTENT_RUN_XML)
    files.set(documentPath, withAltContent)
  }

  return { id, document, postProcess }
}

