// 5. Styled / banded table (custom table style with real w:tblStylePr)
// ---------------------------------------------------------------------------
const BANDED_TABLE_STYLE_ID = 'AtlasBandedTable'
const BANDED_TABLE_STYLE_XML = `
<w:style w:type="table" w:customStyle="1" w:styleId="${BANDED_TABLE_STYLE_ID}">
  <w:name w:val="Atlas Banded Table"/>
  <w:basedOn w:val="TableNormal"/>
  <w:tblPr>
    <w:tblStyleRowBandSize w:val="1"/>
    <w:tblStyleColBandSize w:val="1"/>
  </w:tblPr>
  <w:tblStylePr w:type="firstRow">
    <w:rPr><w:b/><w:color w:val="FFFFFF"/></w:rPr>
    <w:tcPr><w:shd w:val="clear" w:color="auto" w:fill="4472C4"/></w:tcPr>
  </w:tblStylePr>
  <w:tblStylePr w:type="band1Horz">
    <w:tcPr><w:shd w:val="clear" w:color="auto" w:fill="D9E2F3"/></w:tcPr>
  </w:tblStylePr>
</w:style>`.replace(/>\s+</g, '><').trim()

function fixtureTableStyledBanded() {
  const id = 'table-styled-banded'
  const cell = (text) => new TableCell({ children: [new Paragraph({ children: [new TextRun(text)] })] })
  const row = (a, b, c) => new TableRow({ children: [cell(a), cell(b), cell(c)] })

  const table = new Table({
    columnWidths: [3000, 3000, 3000],
    style: BANDED_TABLE_STYLE_ID,
    tableLook: { firstRow: true, lastRow: false, firstColumn: false, lastColumn: false, noHBand: false, noVBand: true },
    rows: [row('Header A', 'Header B', 'Header C'), row('R1 A', 'R1 B', 'R1 C'), row('R2 A', 'R2 B', 'R2 C'), row('R3 A', 'R3 B', 'R3 C')],
  })

  const document = new Document({
    creator: AUTHOR,
    lastModifiedBy: AUTHOR,
    sections: [{ children: [introParagraph(id), table] }],
  })

  const postProcess = (files) => {
    const stylesPath = 'word/styles.xml'
    const xml = files.get(stylesPath)
    if (typeof xml !== 'string' || !xml.includes('</w:styles>')) {
      throw new Error(`${id}: expected ${stylesPath} to contain a closing </w:styles> tag`)
    }
    files.set(stylesPath, xml.replace('</w:styles>', `${BANDED_TABLE_STYLE_XML}</w:styles>`))
  }

  return { id, document, postProcess }
}

